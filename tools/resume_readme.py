"""Generate README.md from the resume doc.

The resume (docs/resume/seth_borne_resume_general.docx, gitignored) is
the source of truth, the same way each page's .docx is for its copy.js.
This turns it into the README GitHub shows on the repo page.

Commands (from the repo root):
  python tools/resume_readme.py --check   show what --write would change, plus warnings
  python tools/resume_readme.py --write   write README.md

Only the text between the resume:start and resume:end markers is
replaced, so anything written above or below them stays.

The resume has no Word heading styles, so its structure is read from
its formatting:
  1st paragraph                  the name           -> # Seth Borne
  2nd paragraph                  the tagline        -> bold line
  3rd paragraph                  contact, split on |  (phone dropped,
                                 email swapped for the site's address)
  bold, all caps                 a section          -> ## Title Case
  has a tab                      an entry: title, tab, dates -> ### title + dates
  Word list paragraph            a bullet           -> - text
  anything else                  a paragraph (bold runs stay bold)
[ALL CAPS] placeholders are left out, with a warning, so an unfinished
link never reaches the README.

Python standard library only. Steps for updating: how_to_update_resume.md
beside the doc (local, gitignored).
"""

import argparse
import difflib
import re
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

# Same folder: reuse the Word XML helpers from the copy pipeline
from copy_sync import R, w
from term import diff_line, dim, fail, ok, paired, path, warn

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / 'docs' / 'resume' / 'seth_borne_resume_general.docx'
PDF = 'docs/resume/seth_borne_resume_general.pdf'
README = ROOT / 'README.md'
PROFILE = ROOT / 'content' / 'profile.js'

START = '<!-- resume:start: generated by tools/resume_readme.py from the resume doc. Edit the doc, not this. -->'
END = '<!-- resume:end -->'

# Kept in capitals when a heading is turned into Title Case
ACRONYMS = {'GIS', 'WAGISA', 'UW', 'DNR', 'YP-SIG', 'AWS', 'MVVA'}
SMALL_WORDS = {'a', 'an', 'the', 'and', 'but', 'or', 'nor', 'for', 'so', 'yet',
               'as', 'at', 'by', 'in', 'of', 'on', 'to', 'up', 'via'}

PLACEHOLDER = re.compile(r'\[[A-Z][A-Z0-9 ]*\]')
# A placeholder and the "  |  " separator before it
PLACEHOLDER_WITH_SEP = re.compile(r'\s*\|\s*\[[A-Z][A-Z0-9 ]*\]|\[[A-Z][A-Z0-9 ]*\]')
PHONE = re.compile(r'^[\d\s().+-]{7,}$')


# ---------------------------------------------------------------- reading


def runs_of(p, rels):
    """A paragraph as a list of runs: {text, bold, href, tab}.

    Skips tracked deletions, like copy_sync.py. A tab becomes its own
    run, since it splits an entry's title from its dates.
    """
    out = []

    def walk(node, href):
        if node.tag in (w('del'), w('moveFrom')):
            return
        if node.tag == w('hyperlink'):
            href = rels.get(node.get(f'{{{R}}}id'), href)
        if node.tag == w('r'):
            bold = node.find(f'{w("rPr")}/{w("b")}') is not None
            for child in node:
                if child.tag == w('t'):
                    out.append({'text': child.text or '', 'bold': bold, 'href': href, 'tab': False})
                elif child.tag == w('tab'):
                    out.append({'text': '', 'bold': False, 'href': None, 'tab': True})
            return
        for child in node:
            walk(child, href)

    walk(p, None)
    return out


def read_resume(path):
    """[{runs, is_list}] for each paragraph with text."""
    with zipfile.ZipFile(path) as z:
        body = ET.fromstring(z.read('word/document.xml')).find(w('body'))
        rels_xml = ET.fromstring(z.read('word/_rels/document.xml.rels'))
    rels = {r.get('Id'): r.get('Target') for r in rels_xml}
    paragraphs = []
    for p in body.findall(w('p')):
        runs = runs_of(p, rels)
        if ''.join(r['text'] for r in runs).strip():
            is_list = p.find(f'{w("pPr")}/{w("numPr")}') is not None
            paragraphs.append({'runs': runs, 'is_list': is_list})
    return paragraphs


def site_email():
    """The address the site uses (content/profile.js), without the subject."""
    match = re.search(r"mailto:([^?'\"]+)", PROFILE.read_text(encoding='utf-8'))
    return match.group(1) if match else None


# ---------------------------------------------------------------- converting


def plain(runs):
    return ''.join(r['text'] for r in runs).replace(' ', ' ').strip()


def escape(text):
    """Markdown characters that would otherwise turn into formatting."""
    return re.sub(r'([*_`<])', r'\\\1', text)


def inline(runs):
    """Runs -> Markdown: bold as **...**, links as [text](url).

    Neighboring runs with the same bold and link are merged first; Word
    splits runs at random points (spell check, edits). Spaces stay
    outside the ** so the bold renders.
    """
    groups = []
    for r in runs:
        if r['tab']:
            continue
        if groups and (groups[-1]['bold'], groups[-1]['href']) == (r['bold'], r['href']):
            groups[-1]['text'] += r['text']
        else:
            groups.append(dict(r))
    out = []
    for g in groups:
        text = g['text'].replace(' ', ' ')
        lead = text[: len(text) - len(text.lstrip())]
        trail = text[len(text.rstrip()):]
        core = escape(text.strip())
        if core and g['bold']:
            core = f'**{core}**'
        if core and g['href']:
            core = f'[{core}]({g["href"]})'
        out.append(f'{lead}{core}{trail}')
    return re.sub(r' {2,}', ' ', ''.join(out)).strip()


def title_case(text):
    """'GIS LEADERSHIP & COMMUNITY' -> 'GIS Leadership & Community'."""
    words = text.split()

    def fix(i, word):
        if word.upper() in ACRONYMS:
            return word.upper()
        lower = word.lower()
        if 0 < i < len(words) - 1 and lower in SMALL_WORDS:
            return lower
        return lower[:1].upper() + lower[1:]

    return ' '.join(fix(i, word) for i, word in enumerate(words))


def is_section(runs):
    """A section heading: every letter bold, all caps."""
    text = plain(runs)
    letters = [r for r in runs if r['text'].strip()]
    return text.isupper() and all(r['bold'] for r in letters)


def contact_line(runs, warnings):
    """Split on |, drop the phone, swap the email, keep links."""
    email = site_email()
    parts = []
    for part in plain(runs).split('|'):
        part = part.strip()
        if not part:
            continue
        if PHONE.match(part):
            warnings.append('phone number left out of the README (public on GitHub)')
            continue
        # Word may split a link's text over several runs, so match linked
        # runs whose text is inside this part; the longest wins, so a
        # short run ("sethborne") can't claim the wrong link
        linked = [r for r in runs if r['href'] and r['text'].strip() and r['text'].strip() in part]
        href = max(linked, key=lambda r: len(r['text'].strip()))['href'] if linked else None
        if '@' in part and email:
            parts.append(f'[{email}](mailto:{email})')
        elif href:
            label = 'LinkedIn' if 'linkedin' in href else part
            parts.append(f'[{label}]({href})')
        else:
            parts.append(escape(part))
    return ' · '.join(parts)


def drop_placeholders(runs, warnings):
    """Runs with [ALL CAPS] placeholders taken out, or None to drop the
    whole paragraph (two or more: a line that's mostly placeholders)."""
    text = plain(runs)
    found = PLACEHOLDER.findall(text)
    if not found:
        return runs
    if len(found) >= 2:
        warnings.append(f'placeholders {", ".join(found)}: line left out ("{text[:50]}...")')
        return None
    warnings.append(f'placeholder {found[0]} left out ("{text[:50]}...")')
    # Rebuild as one plain run per original run, removing the token and
    # its separator from the joined text, then trimming
    joined = ''.join(r['text'] for r in runs if not r['tab'])
    cleaned = PLACEHOLDER_WITH_SEP.sub('', joined).rstrip(' |')
    # Keep bold/link where the text is unchanged: cut the runs at the
    # cleaned length (placeholders sit at the end of their lines)
    out, used = [], 0
    for r in runs:
        if r['tab']:
            out.append(r)
            continue
        room = len(cleaned) - used
        if room <= 0:
            break
        piece = r['text'][:room]
        out.append({**r, 'text': piece})
        used += len(piece)
    return out


def to_markdown(paragraphs):
    """(markdown body, warnings)."""
    warnings = []
    lines = []

    def block(text):
        # Blank line between blocks, except between bullets of one list
        if lines and not (text.startswith('- ') and lines[-1].startswith('- ')):
            lines.append('')
        lines.append(text)

    for i, para in enumerate(paragraphs):
        runs = para['runs']
        if i == 0:
            block(f'# {title_case(plain(runs))}')
            continue
        if i == 1:
            block(f'**{escape(plain(runs))}**')
            continue
        if i == 2:
            block(contact_line(runs, warnings))
            continue
        runs = drop_placeholders(runs, warnings)
        if not runs or not plain(runs):
            continue
        if is_section(runs):
            block(f'## {title_case(plain(runs))}')
        elif any(r['tab'] for r in runs):
            cut = next(n for n, r in enumerate(runs) if r['tab'])
            title, dates = plain(runs[:cut]), plain(runs[cut + 1:])
            block(f'### {escape(title)}')
            if dates:
                block(f'*{escape(dates)}*')
        elif para['is_list']:
            block(f'- {inline(runs)}')
        else:
            block(inline(runs))

    block(f'Generated from my resume by `tools/resume_readme.py`. [Resume (PDF)]({PDF})')
    return '\n'.join(lines), warnings


def with_section(readme, body):
    """README text with the marked section replaced (or the whole file,
    when it has no markers yet)."""
    section = f'{START}\n\n{body}\n\n{END}'
    if START.split(':')[0] in readme and END in readme:
        before = readme.split('<!-- resume:start')[0]
        after = readme.split(END, 1)[1]
        return f'{before}{section}{after}'
    return f'{section}\n'


# ---------------------------------------------------------------- main


def main():
    parser = argparse.ArgumentParser(description='Generate README.md from the resume doc.')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true', help='show what --write would change, plus warnings')
    mode.add_argument('--write', action='store_true', help='write README.md')
    args = parser.parse_args()
    # Windows consoles default to cp1252, which can't print an emoji or an
    # en dash from the old README; replace what can't be shown
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

    if not DOC.exists():
        fail('No Resume Doc', path(DOC.relative_to(ROOT), sys.stderr))
    body, warnings = to_markdown(read_resume(DOC))
    old = README.read_text(encoding='utf-8') if README.exists() else ''
    new = with_section(old, body)

    if old == new:
        print(ok('README.md already matches the resume.'))
    elif args.write:
        README.write_text(new, encoding='utf-8', newline='\n')
        print(ok('Wrote README.md.'), dim('Review with: git diff README.md (or Source Control)'))
    else:
        diff = difflib.unified_diff(old.splitlines(), new.splitlines(), 'README.md', 'README.md (new)', lineterm='')
        print('\n'.join(diff_line(line) for line in paired(diff)))
        print(f'\n{warn("README.md would change.")} {dim("Run --write to apply.")}')

    if warnings:
        print(f'\n{warn(f"{len(warnings)} warning(s):")}')
        print('\n'.join(warn(f'  {line}') for line in warnings))


if __name__ == '__main__':
    main()
